// The examples published on GitHub Pages. Adding an example to the site is one row here.

/** Builds a Vite example with the inspector on, under its Pages base path. */
const vite = (name) => (base) => [
  "--filter",
  `@prosemirror-devtools/${name}-demo`,
  "exec",
  "vite",
  "build",
  "--base",
  base,
  "--outDir",
  "pages-dist",
  "--emptyOutDir",
];

